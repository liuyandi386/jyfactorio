#pragma once
// =====================================================================
// Position.h —— 位置组件
//
// GridPos: 网格坐标（建筑等按格子放置的实体，单位: 格）
// WorldPos: 世界像素坐标（敌人/子弹等连续移动的实体，单位: 像素）
// =====================================================================

/// 网格坐标（建筑）
struct GridPos {
    int x = 0;
    int y = 0;
};

/// 世界像素坐标（连续移动实体）
struct WorldPos {
    float x = 0.0f;
    float y = 0.0f;
};
